/**
 * Extracts the SVG bodies of the icons the app uses from the Iconify JSON packages and writes
 * `src/lib/icons.generated.ts`. Deterministic: same inputs, byte-identical output.
 */
import { mappedIconNames } from '@shinobi/content';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { SHELL_GAME_ICONS, UI_ICON_NAMES } from '../src/lib/ui-icons.ts';

interface IconifyIcon {
  body: string;
  width?: number;
  height?: number;
}

interface IconifySet {
  width?: number;
  height?: number;
  icons: Record<string, IconifyIcon>;
  aliases?: Record<string, { parent: string }>;
}

const require = createRequire(import.meta.url);

function load(pkg: string): IconifySet {
  return JSON.parse(readFileSync(require.resolve(`${pkg}/icons.json`), 'utf8')) as IconifySet;
}

/** The `body` strings of the requested icons, sorted by name. Fails on an unknown name. */
export function extract(set: IconifySet, names: readonly string[], label: string) {
  const out: Record<string, string> = {};
  for (const name of [...new Set(names)].sort()) {
    const direct = set.icons[name];
    const parent = set.aliases?.[name]?.parent;
    const icon = direct ?? (parent === undefined ? undefined : set.icons[parent]);
    if (!icon) throw new Error(`${label}: icon "${name}" is not in the collection`);
    if (
      (icon.width !== undefined && icon.width !== set.width) ||
      (icon.height !== undefined && icon.height !== set.height)
    ) {
      throw new Error(`${label}: icon "${name}" has its own size; the viewBox would be wrong`);
    }
    out[name] = icon.body;
  }
  return { out, size: set.width ?? 16 };
}

export function render(): string {
  const game = extract(
    load('@iconify-json/game-icons'),
    [...mappedIconNames(), ...SHELL_GAME_ICONS],
    'game-icons',
  );
  const lucide = extract(load('@iconify-json/lucide'), UI_ICON_NAMES, 'lucide');

  const block = (record: Record<string, string>) =>
    Object.entries(record)
      .map(([name, body]) => `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`)
      .join('\n');

  return `/* eslint-disable */
// Generated by \`pnpm icons:build\` from @iconify-json/game-icons (CC BY 3.0) and @iconify-json/lucide (ISC).
// Do not edit by hand. Only the icons the app uses are included.

/** Icon bodies from game-icons.net, drawn on a ${game.size}x${game.size} grid. */
export const GAME_ICON_SIZE = ${game.size};
export const GAME_ICONS: Readonly<Record<string, string>> = {
${block(game.out)}
};

/** Icon bodies from Lucide, drawn on a ${lucide.size}x${lucide.size} grid. */
export const LUCIDE_ICON_SIZE = ${lucide.size};
export const LUCIDE_ICONS: Readonly<Record<string, string>> = {
${block(lucide.out)}
};
`;
}

const target = fileURLToPath(new URL('../src/lib/icons.generated.ts', import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render();
  writeFileSync(target, text);
  console.log(`icons: wrote ${text.length} bytes to ${target}`);
}
