export type CoreApiName =
  | (typeof CORE_API)['constants'][number]
  | (typeof CORE_API)['formulas'][number]
  | (typeof CORE_API)['state'][number]
  | (typeof CORE_API)['world'][number]
  | (typeof CORE_API)['forecasts'][number];

/** The names, flat. */
export const CORE_API_NAMES: readonly CoreApiName[] = Object.values(CORE_API).flat();

/** The part of the core that packs see. */
export type CoreApi = Readonly<Pick<typeof core, CoreApiName>>;

/** The allowed part of the core, frozen. */
export const corePublic: CoreApi = Object.freeze(
  Object.fromEntries(CORE_API_NAMES.map((name) => [name, (core as Record<string, unknown>)[name]])),
) as CoreApi;
